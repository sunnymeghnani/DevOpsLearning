#!/bin/bash
# Room 11 (http-curl): an HTTPS redirect loop, and a certificate from the internal CA that this box doesn't trust.
# Broken state:
#  - shop.example.com:443 has "try_files / =404;" -> every URL answers 301 to https://shop.example.com/ (itself);
#  - the leaf is signed by "Example Internal CA" (/etc/ssl/example-ca/ca.crt), which is not in the system trust store
#    -> curl without -k: "(60) SSL certificate problem: unable to get local issuer certificate".
set -euo pipefail

# the lab image also carries apache2, whose package puts its own index.html into /var/www/html; nginx's
# default site lists index.html first, so drop it to keep the stock "Welcome to nginx!" page the brief describes
rm -f /var/www/html/index.html

# name -> this box (/etc/hosts is a bind mount here: rewrite in place)
grep -v 'shop\.example\.com' /etc/hosts > /tmp/.hosts.$$ || true
echo '127.0.0.1 shop.example.com' >> /tmp/.hosts.$$
cat /tmp/.hosts.$$ > /etc/hosts && rm -f /tmp/.hosts.$$

# internal CA + server certificate (the CA key leaves the box: only IT can sign)
if [ -e /usr/local/share/ca-certificates/example-internal-ca.crt ] || ls /usr/local/share/ca-certificates/ | grep -qi example; then
  rm -f /usr/local/share/ca-certificates/*xample*
  update-ca-certificates --fresh >/dev/null 2>&1
fi
install -d -m 0755 /etc/ssl/example-ca /etc/nginx/ssl
w=$(mktemp -d)
openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -days 3650 \
  -subj "/O=Example Org/CN=Example Internal CA" -keyout "$w/ca.key" -out /etc/ssl/example-ca/ca.crt \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
openssl req -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -subj "/O=Example Org/CN=shop.example.com" \
  -keyout /etc/nginx/ssl/shop.example.com.key -out "$w/shop.csr" 2>/dev/null
printf 'subjectAltName=DNS:shop.example.com\nbasicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\n' > "$w/ext"
openssl x509 -req -in "$w/shop.csr" -CA /etc/ssl/example-ca/ca.crt -CAkey "$w/ca.key" -CAcreateserial \
  -days 397 -extfile "$w/ext" -out /etc/nginx/ssl/shop.example.com.crt 2>/dev/null
rm -rf "$w"
chmod 0644 /etc/ssl/example-ca/ca.crt /etc/nginx/ssl/shop.example.com.crt
chmod 0600 /etc/nginx/ssl/shop.example.com.key
cat > /etc/ssl/example-ca/README <<'EOF'
Example Internal CA - root certificate (ca.crt). Distributed by IT.
Every server that calls internal HTTPS services must trust it.
EOF

# the site
install -d /var/www/shop/docs
echo '<!doctype html><title>Shop</title><h1>Shop</h1><p>Autumn sale.</p>' > /var/www/shop/index.html
echo '<!doctype html><title>Docs</title><h1>Shop docs</h1>' > /var/www/shop/docs/index.html
cat > /etc/nginx/sites-available/shop <<'EOF'
# shop.example.com - generated by provision-web.sh v0.3
server {
    listen 80;
    server_name shop.example.com;
    return 301 https://$host$request_uri;
}

server {
    listen 443 ssl;
    server_name shop.example.com;
    ssl_certificate     /etc/nginx/ssl/shop.example.com.crt;
    ssl_certificate_key /etc/nginx/ssl/shop.example.com.key;

    root /var/www/shop;
    index index.html;

    location = /health {
        default_type text/plain;
        return 200 "ok\n";
    }

    location / {
        try_files / =404;
    }
}
EOF
ln -sfn /etc/nginx/sites-available/shop /etc/nginx/sites-enabled/shop
[ -e /etc/nginx/sites-enabled/default ] || ln -s /etc/nginx/sites-available/default /etc/nginx/sites-enabled/default
systemctl enable nginx >/dev/null 2>&1
systemctl restart nginx
