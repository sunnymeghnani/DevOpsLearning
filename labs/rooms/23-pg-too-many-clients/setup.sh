#!/bin/bash
# Room 23 (db-incidents): PostgreSQL "FATAL: sorry, too many clients already".
# Small on purpose: max_connections=20 (3 reserved for superusers), shared_buffers=16MB.
# Broken state:
#  - report-worker.service (user reports) opens a new connection for every batch and never closes it: it holds
#    every free slot and keeps retrying, so the shop app gets "sorry, too many clients already";
#  - two ad-hoc analyst sessions were left "idle in transaction" (started with systemd-run, as if from a tmux);
#  - no idle_session_timeout / idle_in_transaction_session_timeout is set.
set -euo pipefail
PGC=/etc/postgresql/16/main

# --- reset (idempotent)
systemctl stop report-worker.service >/dev/null 2>&1 || true
for u in analyst-adhoc-1 analyst-adhoc-2; do systemctl stop "$u" >/dev/null 2>&1 || true; systemctl reset-failed "$u" >/dev/null 2>&1 || true; done

for u in shop reports analyst; do id "$u" >/dev/null 2>&1 || useradd --system --create-home --shell /bin/bash "$u"; done

cat > $PGC/conf.d/90-lab.conf <<'CONF'
# lab sizing (small on purpose)
max_connections = 20
shared_buffers = 16MB
superuser_reserved_connections = 3
log_connections = off
CONF
# forget earlier fixes from a previous run of this room
[ -f /var/lib/postgresql/16/main/postgresql.auto.conf ] && \
  printf '# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n' > /var/lib/postgresql/16/main/postgresql.auto.conf
systemctl enable postgresql >/dev/null 2>&1
systemctl restart postgresql
for _ in $(seq 1 50); do runuser -u postgres -- pg_isready -q && break; sleep 0.1; done

runuser -u postgres -- psql -q -v ON_ERROR_STOP=1 <<'SQL' >/dev/null
DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'shop')    THEN CREATE ROLE shop LOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'reports') THEN CREATE ROLE reports LOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'analyst') THEN CREATE ROLE analyst LOGIN; END IF;
END $$;
ALTER ROLE reports RESET ALL;
ALTER ROLE analyst RESET ALL;
ALTER ROLE shop RESET ALL;
SELECT 'CREATE DATABASE shop OWNER shop' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'shop')\gexec
SQL
runuser -u postgres -- psql -q -d shop -v ON_ERROR_STOP=1 <<'SQL' >/dev/null
SET client_min_messages = warning;
CREATE TABLE IF NOT EXISTS orders (id serial PRIMARY KEY, total numeric(10,2), created timestamptz DEFAULT now());
ALTER TABLE orders OWNER TO shop;
INSERT INTO orders (total) SELECT 9.99 WHERE NOT EXISTS (SELECT FROM orders);
GRANT SELECT ON orders TO reports, analyst;
SQL

# --- two forgotten analyst sessions: idle in transaction
for n in 1 2; do
  systemd-run --quiet --unit="analyst-adhoc-$n" --uid=analyst --gid=analyst \
    -p Description="ad-hoc psql (analyst)" \
    sh -c "(echo 'BEGIN; SELECT count(*) FROM orders;'; exec sleep infinity) | exec psql -q -d shop >/dev/null"
done

# --- the leaky worker: talks the PostgreSQL wire protocol over the Unix socket (peer auth), never closes
cat > /usr/local/bin/report-worker <<'PY'
#!/usr/bin/env python3
"""report-worker (lab stand-in): opens a new connection per batch and forgets to close it."""
import socket, struct, time

SOCK = "/var/run/postgresql/.s.PGSQL.5432"

def connect():
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.connect(SOCK)
    params = b"".join(k + b"\0" + v + b"\0" for k, v in
                      ((b"user", b"reports"), (b"database", b"shop"), (b"application_name", b"report-worker")))
    body = struct.pack("!I", 196608) + params + b"\0"
    s.sendall(struct.pack("!I", len(body) + 4) + body)
    buf = b""
    while True:
        chunk = s.recv(4096)
        if not chunk:
            raise OSError("server closed the connection")
        buf += chunk
        while len(buf) >= 5:
            kind, ln = buf[:1], struct.unpack("!I", buf[1:5])[0]
            if len(buf) < ln + 1:
                break
            msg, buf = buf[5:ln + 1], buf[ln + 1:]
            if kind == b"E":
                fields = dict((f[:1], f[1:]) for f in msg.split(b"\0") if f)
                raise OSError(fields.get(b"S", b"").decode() + ": " + fields.get(b"M", b"").decode())
            if kind == b"Z":                       # ReadyForQuery: logged in, now forget about it
                q = b"SELECT count(*) FROM orders\0"
                s.sendall(b"Q" + struct.pack("!I", len(q) + 4) + q)
                return s

held = []
batch = 0
while True:
    batch += 1
    try:
        held.append(connect())
        print(f"batch {batch}: exported (connections held: {len(held)})", flush=True)
        time.sleep(0.05 if len(held) < 20 else 2)
    except OSError as e:
        print(f"batch {batch}: FAILED {e}", flush=True)
        time.sleep(5)
PY
chmod 755 /usr/local/bin/report-worker
cat > /etc/systemd/system/report-worker.service <<'UNIT'
[Unit]
Description=Nightly report exporter (batch worker)
After=postgresql.service
Wants=postgresql.service

[Service]
User=reports
ExecStart=/usr/local/bin/report-worker
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable report-worker.service >/dev/null 2>&1
systemctl start report-worker.service

# wait until the slots are gone, then remember when PostgreSQL started (the fix must not need a restart)
for _ in $(seq 1 40); do
  runuser -u shop -- psql -d shop -Atc 'select 1' >/dev/null 2>&1 || break
  sleep 0.2
done
install -d -m 0700 /var/lib/lab-room23
runuser -u postgres -- psql -Atc 'select pg_postmaster_start_time()' > /var/lib/lab-room23/pg-start
runuser -u postgres -- psql -Atc "select pid from pg_stat_activity where usename = 'analyst' and state like 'idle in transaction%'" \
  > /var/lib/lab-room23/stale-pids
